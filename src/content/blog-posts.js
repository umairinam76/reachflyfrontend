export const BLOG_POSTS = Object.freeze([
  ...SEO_BLOG_POSTS,
  ...CORE_BLOG_POSTS,
]);

export const BLOG_CATEGORIES = Object.freeze(
  Array.from(
    BLOG_POSTS.reduce(
      (
        map,
        post
      ) => {
        const category =
          String(
            post?.category ||
              "Uncategorized"
          ).trim() ||
          "Uncategorized";

        map.set(
          category,
          (
            map.get(
              category
            ) ||
            0
          ) +
            1
        );

        return map;
      },
      new Map()
    ).entries()
  )
    .map(
      (
        [
          name,
          count,
        ]
      ) => ({
        name,
        count,
      })
    )
    .sort(
      (
        a,
        b
      ) =>
        b.count -
          a.count ||
        a.name.localeCompare(
          b.name
        )
    )
);

const BLOG_POST_BY_SLUG =
  new Map(
    BLOG_POSTS.map(
      (
        post
      ) => [
        post.slug,
        post,
      ]
    )
  );

export function getBlogPost(
  slug
) {
  const key =
    normalizeSlug(
      slug
    );

  if (!key) {
    return null;
  }

  return (
    BLOG_POST_BY_SLUG.get(
      key
    ) ||
    null
  );
}

export function getRelatedPosts(
  post,
  limit = 3
) {
  if (
    !post?.slug
  ) {
    return [];
  }

  const requested =
    clamp(
      Number(
        limit
      ) ||
        3,
      1,
      12
    );

  return BLOG_POSTS
    .filter(
      (
        candidate
      ) =>
        candidate.slug !==
        post.slug
    )
    .map(
      (
        candidate
      ) => ({
        candidate,
        score:
          relatedScore(
            post,
            candidate
          ),
      })
    )
    .sort(
      (
        a,
        b
      ) =>
        b.score -
          a.score ||
        compareDateDesc(
          a.candidate.updatedAt,
          b.candidate.updatedAt
        ) ||
        a.candidate.title.localeCompare(
          b.candidate.title
        )
    )
    .slice(
      0,
      requested
    )
    .map(
      (
        item
      ) =>
        item.candidate
    );
}

export function searchBlogPosts(
  query,
  {
    category = "All",
    limit,
  } = {}
) {
  const terms =
    normalizeSearchText(
      query
    )
      .split(/\s+/)
      .filter(
        Boolean
      );

  const selectedCategory =
    String(
      category ||
        "All"
    ).trim();

  const matching =
    BLOG_POSTS
      .filter(
        (
          post
        ) =>
          selectedCategory ===
            "All" ||
          post.category ===
            selectedCategory
      )
      .map(
        (
          post
        ) => ({
          post,
          score:
            searchScore(
              post,
              terms
            ),
        })
      )
      .filter(
        (
          item
        ) =>
          !terms.length ||
          item.score >
            0
      )
      .sort(
        (
          a,
          b
        ) =>
          b.score -
            a.score ||
          compareDateDesc(
            a.post.updatedAt,
            b.post.updatedAt
          ) ||
          a.post.title.localeCompare(
            b.post.title
          )
      );

  const result =
    matching.map(
      (
        item
      ) =>
        item.post
    );

  if (
    !Number.isFinite(
      Number(
        limit
      )
    )
  ) {
    return result;
  }

  return result.slice(
    0,
    clamp(
      Number(
        limit
      ),
      1,
      BLOG_POSTS.length
    )
  );
}

